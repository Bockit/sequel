import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, it } from 'node:test'
import {
  compareModules,
  findQueryFolders,
  hasNamedQueries,
  installModules,
  isGeneratedModule,
} from './modules.ts'

const header = (file: string) => `// Generated by sequel from ${file}. Do not edit.\n`

describe('generated modules (TECH-SPEC §9)', () => {
  let root: string
  let folder: string

  beforeEach(async () => {
    root = await mkdtemp(path.join(tmpdir(), 'sequel-modules-'))
    folder = path.join(root, 'src', 'tasks', 'queries')
    await mkdir(folder, { recursive: true })
  })

  afterEach(async () => {
    await rm(root, { recursive: true, force: true })
  })

  it('recognises a module by its header line', () => {
    assert.equal(isGeneratedModule(`${header('a.sql')}\nexport {}\n`), true)
    assert.equal(isGeneratedModule(header('a.sql').trimEnd()), true)
    assert.equal(isGeneratedModule(`\n${header('a.sql')}`), false)
    assert.equal(isGeneratedModule('// Generated by someone else.\n'), false)
  })

  it('finds the folders a glob matches, sorted, skipping node_modules', async () => {
    await mkdir(path.join(root, 'src', 'billing', 'queries'), { recursive: true })
    await mkdir(path.join(root, 'src', 'node_modules', 'x', 'queries'), { recursive: true })
    await writeFile(path.join(root, 'src', 'queries'), 'a file, not a folder')
    assert.deepEqual(await findQueryFolders([path.join(root, 'src/**/queries')]), [
      path.join(root, 'src', 'billing', 'queries'),
      folder,
    ])
  })

  it('gives a block only to folders with a named query', async () => {
    assert.equal(await hasNamedQueries(folder), false)
    await writeFile(path.join(folder, 'seed.sql'), 'SELECT 1;\n')
    assert.equal(await hasNamedQueries(folder), false)
    await writeFile(path.join(folder, 'tasks.sql'), '-- name: GetTask :one\nSELECT 1;\n')
    assert.equal(await hasNamedQueries(folder), true)
  })

  it('writes changed modules, keeps unchanged ones, and deletes orphans', async () => {
    const same = `${header('same.sql')}same\n`
    await writeFile(path.join(folder, 'same.ts'), same)
    await writeFile(path.join(folder, 'old.ts'), `${header('old.sql')}old\n`)
    await writeFile(path.join(folder, 'stale.ts'), `${header('stale.sql')}before\n`)
    await writeFile(path.join(folder, 'mine.ts'), 'export const mine = 1\n')
    const rendered = new Map([
      [
        folder,
        new Map([
          ['same.ts', same],
          ['stale.ts', `${header('stale.sql')}after\n`],
          ['new.ts', `${header('new.sql')}new\n`],
        ]),
      ],
    ])

    assert.deepEqual(await compareModules(rendered, [folder]), {
      stale: [path.join(folder, 'stale.ts')],
      missing: [path.join(folder, 'new.ts')],
      orphaned: [path.join(folder, 'old.ts')],
    })
    assert.deepEqual(await installModules(rendered, [folder]), {
      written: [path.join(folder, 'new.ts'), path.join(folder, 'stale.ts')],
      unchanged: [path.join(folder, 'same.ts')],
      deleted: [path.join(folder, 'old.ts')],
    })
    assert.deepEqual((await readdir(folder)).sort(), ['mine.ts', 'new.ts', 'same.ts', 'stale.ts'])
    assert.equal(
      await readFile(path.join(folder, 'stale.ts'), 'utf8'),
      `${header('stale.sql')}after\n`,
    )
    assert.deepEqual(await compareModules(rendered, [folder]), {
      stale: [],
      missing: [],
      orphaned: [],
    })
  })

  it("refuses to overwrite a file sequel didn't generate, changing nothing", async () => {
    await writeFile(path.join(folder, 'tasks.ts'), 'export const mine = 1\n')
    await writeFile(path.join(folder, 'old.ts'), `${header('old.sql')}old\n`)
    const rendered = new Map([
      [
        folder,
        new Map([
          ['a.ts', `${header('a.sql')}a\n`],
          ['tasks.ts', `${header('tasks.sql')}tasks\n`],
        ]),
      ],
    ])
    await assert.rejects(
      installModules(rendered, [folder]),
      /tasks\.ts was not generated by sequel, and generating would overwrite it\. Rename its query file, or move tasks\.ts out of the query folder\./,
    )
    assert.deepEqual((await readdir(folder)).sort(), ['old.ts', 'tasks.ts'])
  })

  it('deletes orphans in a folder that no longer has a block', async () => {
    await writeFile(path.join(folder, 'gone.ts'), `${header('gone.sql')}gone\n`)
    const result = await installModules(new Map(), [folder])
    assert.deepEqual(result.deleted, [path.join(folder, 'gone.ts')])
  })
})
