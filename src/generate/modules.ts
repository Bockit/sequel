import { glob, readdir, readFile, rm, stat } from 'node:fs/promises'
import path from 'node:path'
import { SequelError } from '../errors.ts'
import { writeAtomically } from '../files.ts'

// R11: the first line of every generated module. sequel recognises its modules, and their
// orphans, by it (TECH-SPEC §9).
const HEADER = /^\/\/ Generated by sequel from .+\. Do not edit\.$/

export function isGeneratedModule(text: string): boolean {
  const newline = text.indexOf('\n')
  return HEADER.test(newline === -1 ? text : text.slice(0, newline))
}

// Every folder a query glob matches, sorted. Each `.sql` file directly inside one is a query
// file; sqlc doesn't read subfolders, so each folder is its own block.
export async function findQueryFolders(patterns: string[]): Promise<string[]> {
  const folders = new Set<string>()
  for (const pattern of patterns) {
    for await (const match of glob(pattern, {
      exclude: (name) => {
        const base = path.basename(name)
        return base === 'node_modules' || base === '.git'
      },
    })) {
      const full = path.resolve(match)
      if ((await stat(full)).isDirectory()) folders.add(full)
    }
  }
  return [...folders].sort()
}

// Whether a folder has a query sqlc will see. A folder of `.sql` files with no named query
// makes sqlc fail ("no queries contained in paths"), so it gets no block.
export async function hasNamedQueries(folder: string): Promise<boolean> {
  for (const name of await sqlFiles(folder)) {
    const text = await readFile(path.join(folder, name), 'utf8')
    if (/^\s*--\s*name:/m.test(text)) return true
  }
  return false
}

async function sqlFiles(folder: string): Promise<string[]> {
  const entries = await readdir(folder, { withFileTypes: true })
  return entries.filter((e) => e.isFile() && e.name.endsWith('.sql')).map((e) => e.name)
}

// The modules a run produced, by folder, then by file name.
export type Rendered = Map<string, Map<string, string>>

export type InstallResult = { written: string[]; unchanged: string[]; deleted: string[] }

// TECH-SPEC §9: puts a successful run's modules in place, and deletes generated modules the
// run didn't produce, because their query file is gone or has no named queries.
// It refuses, changing nothing, to overwrite a `.ts` file sequel didn't generate.
export async function installModules(
  rendered: Rendered,
  folders: string[],
): Promise<InstallResult> {
  const plan = await planModules(rendered, folders)
  const clobbered = plan.changed.filter(
    (change) => change.existing !== undefined && !isGeneratedModule(change.existing),
  )
  if (clobbered.length > 0) {
    throw new SequelError(
      clobbered
        .map(
          ({ file }) =>
            `${file} was not generated by sequel, and generating would overwrite it. Rename its query file, or move ${path.basename(file)} out of the query folder.`,
        )
        .join('\n'),
    )
  }
  for (const { file, contents } of plan.changed) await writeAtomically(file, contents)
  for (const file of plan.orphaned) await rm(file, { force: true })
  return {
    written: plan.changed.map((change) => change.file),
    unchanged: plan.unchanged,
    deleted: plan.orphaned,
  }
}

export type ModuleCheck = { stale: string[]; missing: string[]; orphaned: string[] }

// For `check`: compares a run's modules with those in place, byte for byte, writing nothing.
export async function compareModules(rendered: Rendered, folders: string[]): Promise<ModuleCheck> {
  const plan = await planModules(rendered, folders)
  return {
    stale: plan.changed.filter((c) => c.existing !== undefined).map((c) => c.file),
    missing: plan.changed.filter((c) => c.existing === undefined).map((c) => c.file),
    orphaned: plan.orphaned,
  }
}

type Plan = {
  changed: { file: string; contents: string; existing: string | undefined }[]
  unchanged: string[]
  orphaned: string[]
}

async function planModules(rendered: Rendered, folders: string[]): Promise<Plan> {
  const plan: Plan = { changed: [], unchanged: [], orphaned: [] }
  const allFolders = [...new Set([...folders, ...rendered.keys()])].sort()
  for (const folder of allFolders) {
    const modules = rendered.get(folder) ?? new Map<string, string>()
    for (const name of [...modules.keys()].sort()) {
      const file = path.join(folder, name)
      const contents = modules.get(name) as string
      const existing = await readIfExists(file)
      if (existing === contents) plan.unchanged.push(file)
      else plan.changed.push({ file, contents, existing })
    }
    let entries: string[]
    try {
      entries = (await readdir(folder, { withFileTypes: true }))
        .filter((e) => e.isFile() && e.name.endsWith('.ts'))
        .map((e) => e.name)
        .sort()
    } catch {
      continue
    }
    for (const name of entries) {
      if (modules.has(name)) continue
      const file = path.join(folder, name)
      const text = await readIfExists(file)
      if (text !== undefined && isGeneratedModule(text)) plan.orphaned.push(file)
    }
  }
  return plan
}

async function readIfExists(file: string): Promise<string | undefined> {
  try {
    return await readFile(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined
    throw error
  }
}
